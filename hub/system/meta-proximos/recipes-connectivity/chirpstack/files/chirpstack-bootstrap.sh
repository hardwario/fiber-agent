#!/bin/sh
# ChirpStack credential bootstrap. Installed as /usr/bin/chirpstack-bootstrap.sh,
# run once per device by chirpstack-bootstrap.service (see that unit for the
# skip-if-present rule, the ordering and why this runs as root).
#
# plan/control/radio/lorawan.md §4, Option B - offline bootstrap. Two ChirpStack
# CLI subcommands against the rendered config, both of which work before the API
# server has ever started, plus the ownership fixups that turn a root-created
# /data/chirpstack into the daemon's own tree:
#
#   1. create-api-key -> the admin-scoped token control-radio needs for tenant
#      resolution and ApplicationService.Create. The other two tokens (tenant,
#      read-only) are minted later by `proximosctl control.radio create`, because
#      minting them needs a tenant id that only a running API can resolve.
#   2. set-password  -> replaces the factory `admin`/`admin`. The result is that
#      the default credential never exists on a listening socket at all.
#   3. copy admin-password -> a `proximos`-readable copy in control-radio's own
#      state tree, because radio-setup runs `control.radio create` as `proximos`
#      and cannot read the 0600 root:root original inside the 0700 chirpstack dir.
#      Without it the first converge dies reading the password and no tenant/
#      read-only token is ever minted.
#
# VERIFIED LIVE against the 4.19.1 binary on 2026-08-27, because both flag
# spellings have already been wrong once in this plan's history (the published
# CLI page still calls step 2 `reset-password`):
#   chirpstack --config <DIR> create-api-key --name <NAME>
#   chirpstack --config <DIR> set-password --email <EMAIL> --password-file <FILE>
# and `create-api-key` prints two plain lines to STDOUT - `id: <uuid>` then
# `token: <jwt>` - interleaved with tracing's own INFO lines, which also go to
# stdout. Hence the line-anchored parse below rather than "the last line".
set -eu

CONFIG_DIR="/run/proximos/chirpstack"
CONFIG_FILE="${CONFIG_DIR}/chirpstack.toml"
DATA_DIR="/data/chirpstack"
PASSWORD_FILE="${DATA_DIR}/admin-password"
SECRET_FILE="${DATA_DIR}/api-secret"
TOKEN_DIR="/data/proximos/radio/lorawan"
TOKEN_FILE="${TOKEN_DIR}/chirpstack-api-token-admin"
# control-radio (radio-setup, running as `proximos`) reads the admin password from here to mint
# the tenant/read-only tokens on first boot. A copy in the component's own 0750 proximos tree,
# because the canonical PASSWORD_FILE is 0600 root:root inside the 0700 chirpstack dir and
# `proximos` cannot read it. Cross-file contract with bootstrap.rs (ADMIN_PASSWORD_FILE).
RADIO_PASSWORD_FILE="${TOKEN_DIR}/chirpstack-admin-password"

# The name is a cross-file contract with control-radio's bootstrap.rs
# (KEY_NAME_PREFIX / `control-radio-admin`): that is how the tenant/readonly mint
# path recognises and prunes rows this step created.
KEY_NAME="control-radio-admin"

# Absolute, like every other path in this script: a
# bare name would resolve through whatever PATH systemd happened to hand this
# unit, and this is the one process on the device that mints a credential.
CHIRPSTACK="/usr/bin/chirpstack"

ADMIN_USER="admin"

log() { echo "chirpstack-bootstrap: $*"; }
die() { echo "chirpstack-bootstrap: $*" >&2; exit 1; }

# The temp file never contains anything but the token, and it is created under
# umask 077 - but a failure between creation and the mv would otherwise leave a
# 0600 copy of a live credential lying around under a name nothing cleans up.
#
# The trailing `return 0` is load-bearing, not tidiness: an EXIT trap's last
# command supplies the script's exit status, so on the success path (where the
# variable has already been cleared) the bare test would evaluate false and turn
# a completed bootstrap into a failed unit. The retired proximos-render.sh shim
# learned this the expensive way - its unit's RuntimeDirectory= was then torn
# down, deleting the config it had just written.
tmp_token=""
tmp_radio_pw=""
cleanup() {
    [ -n "${tmp_token}" ] && [ -f "${tmp_token}" ] && rm -f "${tmp_token}"
    [ -n "${tmp_radio_pw}" ] && [ -f "${tmp_radio_pw}" ] && rm -f "${tmp_radio_pw}"
    return 0
}
trap cleanup EXIT

# --- prerequisites -----------------------------------------------------------
#
# chirpstack-bootstrap.service's ConditionPathExists= covers the config file
# already; this repeats it so that a hand-run of this script for diagnosis fails
# with a sentence instead of a ChirpStack backtrace.
[ -f "${CONFIG_FILE}" ] || die "${CONFIG_FILE} does not exist - the renderer emits it only when radio.mode is lorawan or dual, so there is nothing to bootstrap"

# Generated by migration 005-chirpstack-seed.sh, which this same package ships.
# Both are checked before anything is created, because a bootstrap that minted a
# token and then could not set the password would leave the device in the one
# state the skip-if-present rule cannot recover from on its own (token present,
# `admin`/`admin` still live).
[ -d "${DATA_DIR}" ] || die "${DATA_DIR} does not exist - migration 005-chirpstack-seed.sh should have created it; check proximos-data-migrate.service"
[ -s "${PASSWORD_FILE}" ] || die "${PASSWORD_FILE} is missing or empty - migration 005-chirpstack-seed.sh generates it; refusing to leave the admin account on its factory password"

# NOT created here, on purpose. This tree is the radio component's
# (010-radio-init.sh, packaged with proximosctl), it is owned by `proximos`, and
# guessing its mode and owner from this side would produce a directory
# control-radio then cannot write - a permission error surfacing two units later,
# in radio-setup, with nothing to point at. The unit's ReadWritePaths= carries a
# `-` prefix for the same reason.
[ -d "${TOKEN_DIR}" ] || die "${TOKEN_DIR} does not exist - it is created by migration 010-radio-init.sh; is the radio component installed and did proximos-data-migrate run?"

# --- 1. mint the admin API key ------------------------------------------------
#
# This is also the step that creates and migrates the database:
# `create-api-key` runs storage::setup() first, which applies ChirpStack's whole
# schema history to /data/chirpstack/chirpstack.sqlite (creating the file if it
# is absent) and sets up a Redis client - which is why the unit is ordered
# After=redis.service and why a first boot works against a virgin /data with no
# server ever having run.
log "minting the ${KEY_NAME} API key (this also creates and migrates the ChirpStack database)"
if ! key_output=$("${CHIRPSTACK}" -c "${CONFIG_DIR}" create-api-key --name "${KEY_NAME}" 2>&1); then
    # The output may carry a redis or SQLite error worth reading; it never
    # carries a token, because there is none when this fails.
    echo "${key_output}" >&2
    die "chirpstack create-api-key failed"
fi

# Line-anchored, and the `p` flag prints only the matches: tracing writes its
# INFO lines to the same stream, so neither "the last line" nor a bare grep would
# be safe. The token itself is never echoed, never passed as an argument, and
# lives only in this shell variable and in the file below (system/design.md §10:
# secrets are read from files, never passed as argv - v1's firstboot exposed them
# in `ps`).
token=$(printf '%s\n' "${key_output}" | sed -n 's/^token: //p')
key_output=""

[ -n "${token}" ] || die "chirpstack create-api-key printed no 'token:' line - the CLI output format changed; nothing has been written"

# A JWT is three base64url segments separated by dots, so the character class
# below is the whole alphabet a valid token can use. It doubles as the guard
# against two `token:` lines (a newline is not in the set) and against a stray
# ANSI escape from the tracing formatter ever ending up inside the value.
case "${token}" in
    *[!A-Za-z0-9._-]*)
        die "the token printed by create-api-key is not a bare JWT - refusing to write it"
        ;;
esac

# umask before the file exists, not a chmod after it: a credential that is even
# briefly world-readable on disk is a credential that leaked. Written to a temp
# name in the destination directory and renamed, so control-radio - which may be
# reading this path at any time - never observes a half-written token.
tmp_token="${TOKEN_DIR}/.chirpstack-api-token-admin.tmp.$$"
( umask 077 && printf '%s\n' "${token}" >"${tmp_token}" )
token=""
chown proximos:proximos "${tmp_token}"
chmod 0600 "${tmp_token}"
mv "${tmp_token}" "${TOKEN_FILE}"
tmp_token=""
log "wrote ${TOKEN_FILE} (0600 proximos:proximos)"

# --- 1b. hand control-radio a readable copy of the admin password -------------
#
# radio-setup.service runs `proximosctl control.radio create` as `proximos`. On a first boot the
# tenant and read-only tokens are absent, so `create` logs in as admin to mint them - which means
# it must read the admin password. The canonical ${PASSWORD_FILE} is 0600 root:root inside the
# 0700 chirpstack directory, which `proximos` cannot even traverse, so reading it there fails with
# EACCES and the whole first-boot converge dies StorageError before a single object is created.
# So write a copy into control-radio's own 0750 proximos state tree, 0600 proximos:proximos, with
# the same umask+temp+rename discipline as the token above so a reader never sees a half-written
# file. (DATA_DIR's recursive chown in step 3 is scoped to /data/chirpstack and never touches this.)
tmp_radio_pw="${TOKEN_DIR}/.chirpstack-admin-password.tmp.$$"
( umask 077 && cat "${PASSWORD_FILE}" >"${tmp_radio_pw}" )
chown proximos:proximos "${tmp_radio_pw}"
chmod 0600 "${tmp_radio_pw}"
mv "${tmp_radio_pw}" "${RADIO_PASSWORD_FILE}"
tmp_radio_pw=""
log "wrote ${RADIO_PASSWORD_FILE} (0600 proximos:proximos) for radio-setup"

# --- 2. replace the factory admin password ------------------------------------
#
# --password-file, not an argument: same rule as above. The file was generated by
# migration 005-chirpstack-seed.sh and stays on /data as the support credential
# for the loopback web UI (lorawan.md §4 documents the ssh -L tunnel that is the
# only way to reach it).
log "setting the ${ADMIN_USER} password from ${PASSWORD_FILE}"
if ! "${CHIRPSTACK}" -c "${CONFIG_DIR}" set-password --email "${ADMIN_USER}" --password-file "${PASSWORD_FILE}"; then
    die "chirpstack set-password failed - the ${ADMIN_USER} account may still carry its factory password"
fi

# --- 3. hand the database to the service account ------------------------------
#
# Everything storage::setup() just created belongs to root, and chirpstack.service
# runs as chirpstack with ReadWritePaths=/data/chirpstack - so without this the
# server cannot open its own database. Recursive because SQLite's -wal and -shm
# files appear beside chirpstack.sqlite and neither their names nor their number
# are this script's business.
chown -R chirpstack:chirpstack "${DATA_DIR}"

# ...except the two seeded secrets, which migration 005 wrote as 0600 root:root
# and which the blunt -R above just took from it. api-secret is the JWT signing
# key for every token in lorawan.md §4's table and admin-password is the human
# support credential; the daemon needs to read neither (the renderer injects the
# secret into the config it reads, and ChirpStack stores only a hash of the
# password). Re-asserting the ownership keeps migration 005 the single authority
# for these two files, so a re-run of it still recognises what it wrote.
for secret in "${SECRET_FILE}" "${PASSWORD_FILE}"; do
    [ -e "${secret}" ] || continue
    chown root:root "${secret}"
    chmod 0600 "${secret}"
done

log "bootstrap complete - chirpstack.service can start"
