"""
Offline verification of the host-side P2P central logic (p2p_proto.py) against
sticker-firmware's OWN known-answer vectors -- no hardware, CI-runnable.

The join vectors come from p2p_join_kat.json, the fixture shared byte-for-byte
with proximos-v2 control-radio (portal/crates/control-radio/tests/fixtures/) and
sticker-firmware (tests/ccm/), sha256
14c4efbd40520d2a48ab3004ba07411e91a4775c87fb93f4663dccf92a8361a5. It was
generated by an independent pycryptodome oracle whose selftest first re-derives
every vector both code bases shipped before #417 / GitLab #73. The CRC vector is
fiber-northbridge tests/hdlc_framing's.

If this harness ever computes a byte differently from the firmware it drives,
these fail before any bench time is spent.

Run:  python3 -m pytest test_p2p_proto.py   (needs pycryptodome)
"""
import json
import pathlib
import struct

import p2p_proto as p

# sticker-firmware tests/ccm KEY
KEY = bytes(range(16))  # 00 01 02 ... 0f

KAT = json.loads((pathlib.Path(__file__).parent / "p2p_join_kat.json").read_text())
KAT_DEV_EUI = bytes.fromhex(KAT["dev_eui"])


def test_hdlc_crc_ccitt_false_reference():
    # fiber-northbridge tests/hdlc_framing: crc16("123456789") == 0x29B1
    assert p.crc16_ccitt_false(b"123456789") == 0x29B1


def test_session_key_known_answer():
    # The shared fixture: dev_nonce=7, central_nonce=0x22222222,
    # dev_eui=70b3d57ed0000abe (MSB-first). Was serial=0x12345678 before #417.
    sk = p.session_key(KEY, KAT["dev_nonce"], KAT["central_nonce"], KAT_DEV_EUI)
    assert sk.hex() == KAT["session_key"]["key"]
    assert sk.hex() == "512894ffc39fd4459d4f65553c870eed"
    # The exact octet string the fixture pins, zero-padded to 32 before CMAC.
    assert p.aes_cmac(KEY, bytes.fromhex(KAT["session_key"]["cmac_input_32"])) == sk


def test_session_key_refuses_a_four_byte_serial():
    # The #118 failure mode: a caller still passing the old serial must fail
    # loudly, not derive a key four bytes different from the node's.
    for bad in (b"\x12\x34\x56\x78", b"", KAT_DEV_EUI + b"\x00"):
        try:
            p.session_key(KEY, 7, 0x22222222, bad)
            assert False, f"{len(bad)}-byte dev_eui accepted"
        except ValueError:
            pass


def test_join_request_tag_known_answer():
    # The shared fixture: header(type=0xF0, ctr=7) + body(product=1, proto=1,
    # dev_eui=70b3d57ed0000abe, fw=1.4.0.0). The tag is CMAC over label+hdr+body,
    # covering 25 B since #417 (was 21 with a 4-byte serial).
    frame = p.build_join_request(KEY, KAT_DEV_EUI, KAT["dev_nonce"])
    assert len(frame) == KAT["join_request"]["frame_len"] == 41
    assert frame.hex() == KAT["join_request"]["frame"]
    assert frame[-p.P2P_JOIN_TAG_LEN:].hex() == KAT["join_request"]["tag"]
    assert frame[-p.P2P_JOIN_TAG_LEN:].hex() == "6897967e0fb26ff1f5961ff4357f2919"


def test_join_accept_tag_known_answer():
    # Deliberately UNCHANGED by #417: the JoinAccept carries no identity field
    # at all, so this is the control that says only the identity moved.
    frame = p.build_join_accept(KEY, dev_nonce=KAT["dev_nonce"], net_id=KAT["net_id"],
                                dev_addr=KAT["dev_addr"], central_nonce=KAT["central_nonce"],
                                rx1_delay_s=KAT["rx1_delay_s"])
    assert frame.hex() == KAT["join_accept"]["frame"]
    assert frame[-p.P2P_JOIN_TAG_LEN:].hex() == "ca91d30e195f4f38bf2af38fc4ead0e0"


def test_join_request_roundtrip_parse():
    # Build a JoinRequest the way the DUT would, then parse+verify it as the central.
    frame = p.build_join_request(KEY, KAT_DEV_EUI, 0x0abbccdd)
    info = p.parse_join_request(frame, KEY)
    assert info["dev_nonce"] == 0x0abbccdd
    assert info["dev_eui"] == "70b3d57ed0000abe"
    assert info["product_type"] == 1 and info["proto_version"] == 1
    assert info["fw"] == (1, 4, 0)
    # The 4th fw_version byte is reserved, and surfaced rather than dropped so the
    # whole 14-byte body can be compared against the other implementations.
    assert info["fw_reserved"] == 0
    assert tuple(info["fw"]) + (info["fw_reserved"],) == tuple(KAT["fw_version"])
    # The pre-#417 37-byte shape must not parse -- a loud break, not a half-read.
    header = p.p2p_header(0, 0, p.FRAME_JOIN_REQUEST, 7)
    body = struct.pack(">BBI", 1, 1, 0x80e007b2) + bytes([1, 4, 0, 0])
    old = header + body + p.aes_cmac(KEY, p.JOIN_TAG_LABEL + header + body)
    assert len(old) == 37
    try:
        p.parse_join_request(old, KEY)
        assert False, "a serial-keyed JoinRequest was accepted"
    except ValueError:
        pass


def test_join_request_bad_tag_rejected():
    header = p.p2p_header(0, 0, p.FRAME_JOIN_REQUEST, 1)
    body = bytes([1, 1]) + KAT_DEV_EUI + bytes([1, 4, 0, 0])
    frame = header + body + (b"\x00" * 16)   # wrong tag
    try:
        p.parse_join_request(frame, KEY)
        assert False, "bad tag accepted"
    except ValueError:
        pass


def test_data_plane_roundtrip_and_ack():
    # session_key from a join, then a telemetry uplink (DIR_TX) the central
    # decrypts, and an ACK (DIR_RX) it builds -- round-trips through the same CCM.
    sk = p.session_key(KEY, 0x00000001, 0xdeadbeef, KAT_DEV_EUI)
    # DUT uplink: telemetry, dev_addr=1, counter=0
    tele = p.build_data_frame(sk, net_id=0xb595cf19, dev_addr=1,
                              frame_type=p.FRAME_TELEMETRY, counter=0,
                              body=b"\x01\x02\x03\x04", direction=p.DIR_TX)
    got = p.decrypt_data_frame(sk, tele, direction=p.DIR_TX)
    assert got["body"] == b"\x01\x02\x03\x04"
    assert got["frame_type"] == p.FRAME_TELEMETRY and got["counter"] == 0
    # central ACK with B1 rssi/snr + B5 time tail
    ack = p.build_ack(sk, net_id=0xb595cf19, dev_addr=1, counter=0,
                      rssi=-56, snr=9, unix_time=1787921251)
    back = p.decrypt_data_frame(sk, ack, direction=p.DIR_RX)
    assert back["frame_type"] == p.FRAME_ACK
    assert back["body"][0] == p.ACK_FLAG_TIME
    assert struct.unpack("b", back["body"][1:2])[0] == -56
    assert struct.unpack(">I", back["body"][3:7])[0] == 1787921251


def test_data_plane_wrong_key_rejected():
    sk = p.session_key(KEY, 1, 2, KAT_DEV_EUI)
    frame = p.build_data_frame(sk, 0, 1, p.FRAME_TELEMETRY, 0, b"hi", p.DIR_TX)
    try:
        p.decrypt_data_frame(p.session_key(KEY, 9, 9, KAT_DEV_EUI), frame, p.DIR_TX)
        assert False, "wrong session_key accepted"
    except ValueError:
        pass


def test_hostmodem_hdlc_roundtrip():
    # A SET_RADIO_CONFIG command encodes and decodes back to the same fields.
    raw = p.enc_set_radio_config(868100000, 10, p.BW_125K, 1, 8, 14, 0)
    frames = list(p.hdlc_decode_frames(raw))
    assert len(frames) == 1
    ftype, seq, body = frames[0]
    assert ftype == p.CMD_SET_RADIO_CONFIG
    freq, sf, bw, cr, pre, pwr, flags = struct.unpack("<IBBBHbB", body)
    assert (freq, sf, bw, cr, pre, pwr, flags) == (868100000, 10, 0, 1, 8, 14, 0)


def test_first_frames_decrypt_under_the_fixture_session_key():
    """The #118 detector: the first frame in each direction under the derived key.

    If the two ends ever disagree on one KDF byte the join still succeeds and only
    this fails -- instead of a bench full of unexplained DECRYPT FAILED lines.
    """
    sk = p.session_key(KEY, KAT["dev_nonce"], KAT["central_nonce"], KAT_DEV_EUI)

    up = KAT["first_telemetry_uplink"]
    got = p.decrypt_data_frame(sk, bytes.fromhex(up["frame"]), direction=p.DIR_TX)
    assert got["body"].hex() == up["plaintext"] == "01082a"
    assert p.p2p_nonce(up["counter"], KAT["dev_addr"], up["frame_type"],
                       up["direction"]).hex() == up["nonce"]

    dn = KAT["first_ack_downlink"]
    got = p.decrypt_data_frame(sk, bytes.fromhex(dn["frame"]), direction=p.DIR_RX)
    assert got["body"].hex() == dn["plaintext"] == "00c407"
    assert p.p2p_nonce(dn["counter"], KAT["dev_addr"], dn["frame_type"],
                       dn["direction"]).hex() == dn["nonce"]
