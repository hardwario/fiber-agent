"""Loader seam: turn TOWER frame KAT files (tower_*_kat.json) into a C header.

Run by CMake at build time over every ccm/tower_*_kat.json (or TOWER_KAT_DIR), so a new
or updated KAT file from the planner is picked up by just dropping it in. Each file holds
"key", "gw_addr", "node_addr" and one object per vector with frame_type, flags, src, dest,
counter and the hex fields plaintext, header, nonce, ciphertext, tag, frame (+ frame_len).

    kat_to_header.py OUT.h IN1.json [IN2.json ...]
"""
import json
import os
import sys

HEX_FIELDS = ("plaintext", "header", "nonce", "ciphertext", "tag", "frame")


def c_bytes(b: bytes) -> str:
    if not b:
        return "{ 0 }"
    return "{ " + ", ".join(f"0x{x:02x}" for x in b) + " }"


def main() -> int:
    if len(sys.argv) < 3:
        sys.stderr.write(__doc__)
        return 2
    out_path, inputs = sys.argv[1], sys.argv[2:]
    lines = [
        "/* GENERATED by tests/tower_codec/kat_to_header.py from:",
        *[f" *   {os.path.basename(p)}" for p in inputs],
        " */",
        "#ifndef TOWER_KAT_H_",
        "#define TOWER_KAT_H_",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "struct tower_kat {",
        "\tconst char *file;",
        "\tconst char *name;",
        "\tuint8_t key[16];",
        "\tuint32_t gw_addr;",
        "\tuint32_t node_addr;",
        "\tuint8_t frame_type;",
        "\tuint8_t flags;",
        "\tuint32_t src;",
        "\tuint32_t dest;",
        "\tuint32_t counter;",
        *[f"\tconst uint8_t *{f};\n\tsize_t {f}_len;" for f in HEX_FIELDS],
        "\tsize_t frame_len_field;",
        "};",
        "",
    ]
    rows = []
    n = 0
    for path in inputs:
        with open(path, encoding="utf-8") as fh:
            doc = json.load(fh)
        key = bytes.fromhex(doc["key"])
        if len(key) != 16:
            raise SystemExit(f"{path}: key must be 16 bytes")
        base = os.path.basename(path)
        for name, v in doc.items():
            if not isinstance(v, dict):
                continue
            fields = {f: bytes.fromhex(v[f]) for f in HEX_FIELDS}
            for f, b in fields.items():
                lines.append(f"static const uint8_t tower_kat_{n}_{f}[] = {c_bytes(b)};")
            refs = " ".join(
                f"tower_kat_{n}_{f}, {len(fields[f])}," for f in HEX_FIELDS
            )
            rows.append(
                f'\t{{ "{base}", "{name}", {c_bytes(key)}, {doc["gw_addr"]}u,'
                f' {doc["node_addr"]}u,\n'
                f'\t  {v["frame_type"]}, {v["flags"]}, {v["src"]}u, {v["dest"]}u,'
                f' {v["counter"]}u,\n'
                f"\t  {refs} {v.get('frame_len', len(fields['frame']))} }},"
            )
            n += 1
    if n == 0:
        raise SystemExit("no KAT vectors found")
    lines.append("")
    lines.append("static const struct tower_kat tower_kats[] = {")
    lines.extend(rows)
    lines.append("};")
    lines.append("")
    lines.append("#endif /* TOWER_KAT_H_ */")
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
