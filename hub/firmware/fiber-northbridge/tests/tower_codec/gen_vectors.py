"""Generate src/ccm_py_vectors.h: AES-128-CCM (13 B nonce, 8 B tag) reference vectors.

Independent of the TOWER KAT (ccm/tower_*_kat.json, generated from the upstream Rust
crates): these come from Python `cryptography` AESCCM, with a fixed seed so the committed
header is reproducible. Covers the AAD / payload length edges of the CBC-MAC padding and
the CTR block boundary, up to the 233 B P0 payload limit.

    python3 gen_vectors.py > src/ccm_py_vectors.h
"""
import random
import sys

from cryptography.hazmat.primitives.ciphers.aead import AESCCM

SEED = 0x70574552  # "TOWR"
# (aad_len, pt_len): empty / partial / exact / one-over blocks, the 14 and 17 B headers,
# the 74 B TOWER cap and the 233 B P0 cap.
CASES = [
    (0, 0), (0, 1), (0, 16), (1, 0), (14, 0), (14, 6), (14, 15), (14, 16), (14, 17),
    (14, 31), (14, 32), (14, 74), (14, 233), (17, 64), (16, 16), (30, 5), (255, 40),
]


def c_bytes(b: bytes, indent: str = "\t") -> str:
    if not b:
        return "{ 0 }"
    if len(b) <= 8:
        return "{ " + ", ".join(f"0x{x:02x}" for x in b) + " }"
    rows = [", ".join(f"0x{x:02x}" for x in b[i:i + 12]) for i in range(0, len(b), 12)]
    return "{\n" + ",\n".join(indent + r for r in rows) + ",\n}"


def main() -> None:
    rng = random.Random(SEED)
    out = [
        "/* SPDX-License-Identifier: Apache-2.0",
        " *",
        " * GENERATED by tests/tower_codec/gen_vectors.py (Python cryptography AESCCM,",
        f" * seed 0x{SEED:08x}, tag_length=8). Do not edit.",
        " */",
        "#ifndef CCM_PY_VECTORS_H_",
        "#define CCM_PY_VECTORS_H_",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "struct ccm_py_vec {",
        "\tconst uint8_t *key;   /* 16 B */",
        "\tconst uint8_t *nonce; /* 13 B */",
        "\tsize_t aad_len;",
        "\tconst uint8_t *aad;",
        "\tsize_t pt_len;",
        "\tconst uint8_t *pt;",
        "\tconst uint8_t *ct;",
        "\tconst uint8_t *tag;   /* 8 B */",
        "};",
        "",
    ]
    rows = []
    for i, (alen, plen) in enumerate(CASES):
        key = bytes(rng.randrange(256) for _ in range(16))
        nonce = bytes(rng.randrange(256) for _ in range(13))
        aad = bytes(rng.randrange(256) for _ in range(alen))
        pt = bytes(rng.randrange(256) for _ in range(plen))
        sealed = AESCCM(key, tag_length=8).encrypt(nonce, pt, aad if alen else None)
        ct, tag = sealed[:-8], sealed[-8:]
        out.append(f"static const uint8_t ccm_py_aad_{i}[] = {c_bytes(aad)};")
        out.append(f"static const uint8_t ccm_py_pt_{i}[] = {c_bytes(pt)};")
        out.append(f"static const uint8_t ccm_py_ct_{i}[] = {c_bytes(ct)};")
        out.append(f"static const uint8_t ccm_py_key_{i}[] = {c_bytes(key)};")
        out.append(f"static const uint8_t ccm_py_nonce_{i}[] = {c_bytes(nonce)};")
        out.append(f"static const uint8_t ccm_py_tag_{i}[] = {c_bytes(tag)};")
        rows.append(
            f"\t{{ ccm_py_key_{i}, ccm_py_nonce_{i}, {alen}, ccm_py_aad_{i}, {plen},"
            f" ccm_py_pt_{i},\n\t  ccm_py_ct_{i}, ccm_py_tag_{i} }},"
        )
    out.append("")
    out.append("static const struct ccm_py_vec ccm_py_vectors[] = {")
    out.extend(rows)
    out.append("};")
    out.append("")
    out.append("#endif /* CCM_PY_VECTORS_H_ */")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
