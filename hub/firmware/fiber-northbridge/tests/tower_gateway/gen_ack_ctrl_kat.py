"""Generate plan/control/radio/p2p_tower_ack_ctrl_kat.txt: TOWER ACK frames with a CTRL
TLV tail (#470 §13.5, N1 part A), shared by the Northbridge and the STICKER node.

An independent model of the spec, not of the C code: the answers are computed here from
§13.5 / §8.2 and sealed with Python `cryptography` AESCCM under the session key, gateway
and node address of tower_frame_kat.json. The hb_* lines carry plaintexts written out by
hand below (not computed) and are only sealed here.

    gen_ack_ctrl_kat.py > ../../../../plan/control/radio/p2p_tower_ack_ctrl_kat.txt
"""
import math
import re
import struct

from cryptography.hazmat.primitives.ciphers.aead import AESCCM

KEY = bytes(range(16))  # tower_frame_kat.json "key"
GW = 0x4E420001         # tower_frame_kat.json "gw_addr" (1312948225)
NODE = 0x00000413       # tower_frame_kat.json "node_addr" (1043)

T_DATA, T_ACK = 0, 1
CONFIRMED = 0x01
PENDING, CTRL = 0x01, 0x02
LINK_CHECK, TIME = 0x10, 0x20


def seal(typ: int, flags: int, src: int, dest: int, ctr: int, pt: bytes) -> bytes:
    hdr = bytes([(1 << 5) | typ, flags]) + struct.pack("<III", src, dest, ctr)
    nonce = struct.pack("<II", src, ctr) + b"\x00" * 5
    return hdr + AESCCM(KEY, tag_length=8).encrypt(nonce, pt, hdr)


def clamp8(v: int) -> int:
    return max(-128, min(127, v))


def link_check_ans(rssi: int, snr_q: int, sf: int) -> bytes:
    # The central's formula (control.rs LinkCheckAns::from_reception): SNR and the margin
    # over the SF demodulation floor (-7.5 dB at SF7, 2.5 dB lower per step), rounded down.
    snr = snr_q / 4.0
    floor_db = -7.5 - 2.5 * (sf - 7)
    return struct.pack("<bbbB", clamp8(rssi), clamp8(math.floor(snr)),
                       clamp8(math.floor(snr - floor_db)), 1)


def time_ans(unix_ms: int, req_counter: int) -> bytes:
    # unix(4 LE) | fraction in 1/256 s, rounded down | req_counter(4 LE)
    return struct.pack("<IBI", unix_ms // 1000, (unix_ms % 1000) * 256 // 1000, req_counter)


def tlv(i: int, v: bytes) -> bytes:
    return bytes([i, len(v)]) + v


def answers(up_pt: bytes, rssi: int, snr_q: int, sf: int, t_rx: int, anchor, ctr: int):
    """The tail the gateway appends, or b'' (no request, a malformed list, no anchor)."""
    if not up_pt or up_pt[0] != 0x91:
        return b""
    ids, b = set(), up_pt[1:]
    while b:
        if len(b) < 2 or len(b) - 2 < b[1]:
            return b""  # a truncated list is not trusted (like the central's parse_tlvs)
        ids.add(b[0])
        b = b[2 + b[1]:]
    tail = b""
    if LINK_CHECK in ids:
        tail += tlv(LINK_CHECK, link_check_ans(rssi, snr_q, sf))
    if TIME in ids and anchor is not None:
        now_ms, unix_ms = anchor
        tail += tlv(TIME, time_ans(unix_ms + (t_rx - now_ms), ctr))
    return tail


def hx(b: bytes) -> str:
    return b.hex() if b else "-"


def ack_line(name, up_ctr, up_pt, rssi, snr_q, sf, t_rx, anchor, pending, ack_ctr,
             up_flags=CONFIRMED):
    up = seal(T_DATA, up_flags, NODE, GW, up_ctr, up_pt)
    tail = answers(up_pt, rssi, snr_q, sf, t_rx, anchor, up_ctr)
    flags = (PENDING if pending else 0) | (CTRL if tail else 0)
    ack_pt = struct.pack("<Ib", up_ctr, clamp8(rssi)) + bytes([flags]) + tail
    ack = seal(T_ACK, 0, GW, NODE, ack_ctr, ack_pt)
    an = f"anchor_now_ms={anchor[0]} anchor_unix_ms={anchor[1]}" if anchor else \
        "anchor_now_ms=- anchor_unix_ms=-"
    return (f"{name} ack up_ctr={up_ctr} up_flags={up_flags} up_pt={hx(up_pt)} "
            f"up_frame={hx(up)} rssi_dbm={rssi} snr_q={snr_q} sf={sf} t_rx_ms={t_rx} {an} "
            f"pending={int(pending)} ack_ctr={ack_ctr} ack_pt={hx(ack_pt)} "
            f"ack_frame={hx(ack)} ack_len={len(ack)}")


def tail_line(name, ack_ctr, ack_pt, note_tlvs):
    ack = seal(T_ACK, 0, GW, NODE, ack_ctr, ack_pt)
    return (f"{name} tail ack_ctr={ack_ctr} ack_pt={hx(ack_pt)} tlvs={note_tlvs} "
            f"ack_frame={hx(ack)} ack_len={len(ack)}")


