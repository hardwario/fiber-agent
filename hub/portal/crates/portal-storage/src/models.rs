/// Filter + pagination for [`crate::Storage::list_alarms`] (rest.md
/// `GET /api/alarms` query params). `limit` is clamped to `1..=1000` by the
/// repo; [`Default`] matches the endpoint defaults (`limit=100`,
/// `include_acknowledged=true`, `include_cleared=true`).
#[derive(Debug, Clone, PartialEq)]
#[cfg_attr(feature = "serde", derive(Serialize, Deserialize))]
pub struct AlarmListFilter {
    pub limit: i64,
    pub offset: i64,
    /// `false` keeps only rows with `acknowledged_at IS NULL`.
    pub include_acknowledged: bool,
    /// `false` keeps only rows with `cleared_at IS NULL` (active alarms).
    pub include_cleared: bool,
    pub hostname: Option<String>,
    /// Inclusive bounds on `triggered_at`, in `audit_log.ts`'s UTC
    /// `YYYY-MM-DD HH:MM:SS` shape: the stored RFC 3339 stamp is compared
    /// with its `T` read as a space, so `/audit` bounds both logs alike.
    pub triggered_since: Option<String>,
    pub triggered_until: Option<String>,
    pub alarm_type: Option<String>,
    pub severity: Option<String>,
    /// Exact `sensor_id` match — the wired probe's encoding (`line-{n}`) is
    /// the whole key, so it has nothing to prefix on.
    pub sensor_id: Option<String>,
    /// `sensor_id` prefix match: `lrw:{node_key}:` for a Node,
    /// `eye:{MAC}:` for a Beacon. Every alarm of one radio probe shares
    /// that prefix and differs only in the field label after it
    /// (`portal_domain::alarm_engine`), so one clause fetches a probe's
    /// whole history — value classes, native slots and MB3's `liveness`
    /// alike.
    ///
    /// Compared with `substr(sensor_id, 1, length(?)) = ?` rather than
    /// `LIKE`: a MAC contains no wildcard today, but `LIKE` would treat one
    /// as a pattern the day an identity did, and `substr` cannot.
    pub sensor_id_prefix: Option<String>,
    /// The quantity (registry field name) the alarm is on: a radio alarm's
    /// `sensor_id` ends in `:{field}`; a wired probe (no `:` in its id)
    /// measures temperature.
    pub sensor_field: Option<String>,
    /// Matches `to_state` — the state the alarm moved *into*. Overlaps
    /// `severity` for WARNING/CRITICAL and adds the three connectivity
    /// states (DISCONNECTED/RECONNECTING/NEVERCONNECTED) it cannot express.
    pub to_state: Option<String>,
    /// Case-insensitive substring over the three columns an operator reads
    /// on the row: the probe's name, its raw id and its location.
    ///
    /// It has to be a SQL clause and not a pass over the rendered page. The
    /// list paginates, so a client-side search answers "not found" for
    /// anything outside the fifty rows on screen — and it looks exactly like
    /// a search that found nothing, which is the failure that made
    /// `alarm_type` a `<select>` instead of a text box.
    pub search: Option<String>,
    /// More ways a row can match `search`, resolved by the caller from
    /// state the database does not hold (the live registry's names):
    /// `(hostname, sensor_id prefix)` pairs, compared case-insensitively.
    /// An empty hostname matches any Hub. Ignored without `search`.
    pub search_targets: Vec<(String, String)>,
    /// Column the page is ordered by. An enum and not a string: the query
    /// string picks a variant or falls back to the default, so nothing a
    /// caller typed ever reaches the ORDER BY as text.
    pub sort: AlarmSort,
    /// Descending when true, which is what every time column wants first.
    pub sort_desc: bool,
}

/// Sortable column of the alarm list. `key` is the name the query string and
/// the table header use; `order_sql` is the expression the repo orders by.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
#[cfg_attr(feature = "serde", derive(Serialize, Deserialize))]
pub enum AlarmSort {
    /// `triggered_at` — the list's default, newest first.
    #[default]
    Start,
    End,
    Location,
    Name,
    Type,
    Value,
}

impl AlarmSort {
    pub fn from_key(key: &str) -> Option<Self> {
        Some(match key {
            "start" => Self::Start,
            "end" => Self::End,
            "loc" => Self::Location,
            "name" => Self::Name,
            "type" => Self::Type,
            "value" => Self::Value,
            _ => return None,
        })
    }

    pub fn key(self) -> &'static str {
        match self {
            Self::Start => "start",
            Self::End => "end",
            Self::Location => "loc",
            Self::Name => "name",
            Self::Type => "type",
            Self::Value => "value",
        }
    }

    /// Ordering expression. The name columns are nullable and collate
    /// case-insensitively so the operator's A-Z matches what they read.
    pub(crate) fn order_sql(self) -> &'static str {
        match self {
            Self::Start => "triggered_at",
            Self::End => "cleared_at",
            Self::Location => "sensor_location COLLATE NOCASE",
            Self::Name => "COALESCE(sensor_name, sensor_id) COLLATE NOCASE",
            Self::Type => "alarm_type COLLATE NOCASE",
            Self::Value => "value",
        }
    }
}

impl Default for AlarmListFilter {
    fn default() -> Self {
        Self {
            limit: 100,
            offset: 0,
            include_acknowledged: true,
            include_cleared: true,
            hostname: None,
            triggered_since: None,
            triggered_until: None,
            alarm_type: None,
            severity: None,
            sensor_id: None,
            sensor_id_prefix: None,
            sensor_field: None,
            to_state: None,
            search: None,
            search_targets: Vec::new(),
            sort: AlarmSort::Start,
            sort_desc: true,
        }
    }
}

