/// One field's summary over a time window — the probe-detail window's
/// aggregate line (plan/portal/monitoring.md §6.2: "počet vzorků · min ·
/// max · avg · med").
///
/// `count` is **stored points**, not samples the device took: the window
/// says what the database holds for the range, which for a wired probe is
/// one `readings_minute` row per minute (decision 2026-09-08 — every wired
/// statistic is computed over `avg_c`, and the count is the number of those
/// rows). A window with no rows is `count = 0` and four `None`s, which is
/// what lets the template say "no data" rather than print `0.0` four times.
#[derive(Debug, Clone, Copy, PartialEq)]
#[cfg_attr(feature = "serde", derive(Serialize, Deserialize))]
pub struct FieldSummary {
    pub count: i64,
    pub min: Option<f64>,
    pub max: Option<f64>,
    pub avg: Option<f64>,
    /// The middle stored value, or the mean of the two middles for an even
    /// count. SQLite has no `median()`, so the repo computes it as an
    /// ordered offset over the same window `count` measures.
    pub median: Option<f64>,
}

impl FieldSummary {
    /// The empty window: no rows, therefore no statistics.
    pub const EMPTY: FieldSummary = FieldSummary {
        count: 0,
        min: None,
        max: None,
        avg: None,
        median: None,
    };
}

/// Which probe a [`SensorEvent`] belongs to — `sensor_events`' three-way
/// identity, the same shape `sensor_group_members` uses (V8/V12).
///
/// An owned enum rather than three `Option` columns on the row structs: the
/// CHECK constraint already makes "exactly one" a database invariant, and
/// repeating it as three nullable fields in Rust invites a caller to pass
/// two.
#[derive(Debug, Clone, PartialEq, Eq)]
#[cfg_attr(feature = "serde", derive(Serialize, Deserialize))]
pub enum ProbeIdentity {
    /// A wired probe's line. `i64` to match the stored column.
    Line(i64),
    /// A Node's `node_key` (lowercase DevEUI).
    Node(String),
    /// A Beacon's MAC, colons and all.
    Mac(String),
}

impl ProbeIdentity {
    /// The three column values to bind, in `(sensor_line, node_key, mac)`
    /// order — exactly one of them non-NULL.
    pub fn columns(&self) -> (Option<i64>, Option<&str>, Option<&str>) {
        match self {
            ProbeIdentity::Line(line) => (Some(*line), None, None),
            ProbeIdentity::Node(key) => (None, Some(key.as_str()), None),
            ProbeIdentity::Mac(mac) => (None, None, Some(mac.as_str())),
        }
    }
}

