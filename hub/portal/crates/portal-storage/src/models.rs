/// Sortable column of the audit log.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
#[cfg_attr(feature = "serde", derive(Serialize, Deserialize))]
pub enum AuditSort {
    /// `ts` — the log's default, newest first.
    #[default]
    Time,
    Event,
    User,
    Ip,
    Target,
    Result,
}

impl AuditSort {
    pub fn from_key(key: &str) -> Option<Self> {
        Some(match key {
            "time" => Self::Time,
            "event" => Self::Event,
            "user" => Self::User,
            "ip" => Self::Ip,
            "target" => Self::Target,
            "result" => Self::Result,
            _ => return None,
        })
    }

    pub fn key(self) -> &'static str {
        match self {
            Self::Time => "time",
            Self::Event => "event",
            Self::User => "user",
            Self::Ip => "ip",
            Self::Target => "target",
            Self::Result => "result",
        }
    }

    pub(crate) fn order_sql(self) -> &'static str {
        match self {
            Self::Time => "ts",
            Self::Event => "event_type COLLATE NOCASE",
            Self::User => "username COLLATE NOCASE",
            Self::Ip => "ip COLLATE NOCASE",
            Self::Target => "target COLLATE NOCASE",
            Self::Result => "success",
        }
    }
}

