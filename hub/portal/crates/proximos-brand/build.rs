//! Turns portal/branding/<PROXIMOS_BRAND>/ into `$OUT_DIR/brand.rs` (plan/portal/branding.md §3).
//!
//! Fails the build, naming the file and what is wrong, on an unknown brand, a malformed or
//! incomplete brand.toml, a splash that is not a 128×64 plain PBM, or a logo/favicon that is a
//! Git LFS pointer instead of the file. There is no fallback to the default brand: a FIBER build
//! that quietly came out as ProXimos is the failure this exists to prevent.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

#[path = "src/parse.rs"]
#[allow(dead_code)]
mod parse;

const DEFAULT: &str = "proximos";

fn fail(msg: String) -> ! {
    eprintln!("proximos-brand: {msg}");
    panic!("proximos-brand: {msg}");
}

fn read(path: &Path) -> String {
    std::fs::read_to_string(path)
        .unwrap_or_else(|e| fail(format!("cannot read {}: {e}", path.display())))
}

/// A file the binary embeds byte for byte. An LFS pointer (a checkout without git-lfs) would
/// otherwise ship as a 130-byte "image".
fn embedded(path: &Path) -> String {
    let bytes = std::fs::read(path)
        .unwrap_or_else(|e| fail(format!("cannot read {}: {e}", path.display())));
    if bytes.starts_with(b"version https://git-lfs.github.com/spec/") {
        fail(format!(
            "{} is a Git LFS pointer, not the file. Install git-lfs and run `git lfs pull`.",
            path.display()
        ));
    }
    format!("{:?}", path.display().to_string())
}

fn main() {
    println!("cargo:rerun-if-env-changed=PROXIMOS_BRAND");
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let root = manifest.join("../../branding");
    let root = root
        .canonicalize()
        .unwrap_or_else(|e| fail(format!("cannot find {}: {e}", root.display())));
    println!("cargo:rerun-if-changed={}", root.display());

    let brand = match std::env::var("PROXIMOS_BRAND") {
        Ok(b) if !b.trim().is_empty() => b.trim().to_string(),
        _ => DEFAULT.to_string(),
    };

    // Every brand is parsed, so a broken brand.toml fails every build, not only its own.
    let mut all = Vec::new();
    let mut entries: Vec<_> = std::fs::read_dir(&root)
        .unwrap_or_else(|e| fail(format!("cannot list {}: {e}", root.display())))
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.join("brand.toml").is_file())
        .collect();
    entries.sort();
    for dir in &entries {
        let toml = parse::brand_toml(&read(&dir.join("brand.toml")))
            .unwrap_or_else(|e| fail(format!("{}/brand.toml: {e}", dir.display())));
        let name = dir.file_name().unwrap().to_string_lossy().to_string();
        if toml["id"] != name {
            fail(format!(
                "{}/brand.toml: id {:?} must match its directory name",
                dir.display(),
                toml["id"]
            ));
        }
        all.push(toml);
    }
    let Some(toml) = all.iter().find(|t| t["id"] == brand) else {
        let known: Vec<&str> = all.iter().map(|t| t["id"].as_str()).collect();
        fail(format!(
            "PROXIMOS_BRAND={brand:?} is not a brand; portal/branding/ has {known:?}"
        ));
    };
    let dir = root.join(&brand);

    let mut out = String::new();
    writeln!(
        out,
        "// Generated by proximos-brand/build.rs from {}.",
        dir.display()
    )
    .unwrap();
    for key in parse::KEYS {
        let name = key.to_ascii_uppercase();
        let value = &toml[key];
        if key.starts_with("docs_pdf_") {
            let v = if value.is_empty() {
                "None".to_string()
            } else {
                format!("Some({value:?})")
            };
            writeln!(out, "pub const {name}: Option<&str> = {v};").unwrap();
        } else {
            writeln!(out, "pub const {name}: &str = {value:?};").unwrap();
        }
    }
    writeln!(
        out,
        "pub const HOSTNAME_PATTERN: &str = {:?};",
        parse::hostname_pattern(&toml["hostname_prefix"])
    )
    .unwrap();

    writeln!(
        out,
        "pub const LOGO_SVG: &[u8] = include_bytes!({});",
        embedded(&dir.join("logo.svg"))
    )
    .unwrap();
    writeln!(
        out,
        "pub const FAVICON_ICO: &[u8] = include_bytes!({});",
        embedded(&dir.join("favicon.ico"))
    )
    .unwrap();

    let splash_path = dir.join("splash.pbm");
    let rows = parse::pbm(&read(&splash_path), 128, 64)
        .unwrap_or_else(|e| fail(format!("{}: {e}", splash_path.display())));
    writeln!(out, "pub static SPLASH: [[u8; 128]; 64] = [").unwrap();
    for row in rows {
        let cells: Vec<String> = row.iter().map(u8::to_string).collect();
        writeln!(out, "    [{}],", cells.join(", ")).unwrap();
    }
    writeln!(out, "];").unwrap();

    let mut overrides = Vec::new();
    for lang in ["en", "cs"] {
        let p = dir.join("i18n").join(format!("{lang}.json"));
        if p.is_file() {
            overrides.push(format!("({lang:?}, include_str!({}))", embedded(&p)));
        }
    }
    writeln!(
        out,
        "pub const I18N_OVERRIDES: &[(&str, &str)] = &[{}];",
        overrides.join(", ")
    )
    .unwrap();

    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("brand.rs");
    std::fs::write(&dest, out)
        .unwrap_or_else(|e| fail(format!("cannot write {}: {e}", dest.display())));
}
