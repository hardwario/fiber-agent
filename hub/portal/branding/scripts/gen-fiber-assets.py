#!/usr/bin/env python3
"""Generate the FIBER brand's raster assets from its SVGs.

    python3 portal/branding/scripts/gen-fiber-assets.py

Writes, next to brand.toml in portal/branding/fiber/:

  favicon.ico   16/32/48/64 px, rendered from icon.svg (Git LFS)
  splash.pbm    the 128x64 ST7920 boot splash: the HARDWARIO mark from
                icon.svg on the left, "FIBER" on the right, 1 bit, plain PBM

Needs inkscape (SVG -> PNG), Pillow, ImageMagick's `convert` (PNG -> ICO) and
DejaVu Sans Bold. The outputs are committed; re-run this after changing
icon.svg instead of editing them. plan/portal/branding.md section 2.
"""
import subprocess
import sys
import tempfile
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

BRAND = Path(__file__).resolve().parents[1] / "fiber"
ICON = BRAND / "icon.svg"
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
W, H = 128, 64


def render(svg: Path, out: Path, size: int, background: bool) -> None:
    cmd = ["inkscape", str(svg), "--export-type=png", f"--export-filename={out}",
           f"--export-width={size}", f"--export-height={size}"]
    if background:
        cmd += ["--export-background=white", "--export-background-opacity=1"]
    subprocess.run(cmd, check=True, capture_output=True)


def favicon(tmp: Path) -> None:
    pngs = []
    for size in (16, 32, 48, 64):
        p = tmp / f"icon-{size}.png"
        render(ICON, p, size, background=False)
        pngs.append(str(p))
    subprocess.run(["convert", *pngs, str(BRAND / "favicon.ico")], check=True)


def splash(tmp: Path) -> None:
    mark_h = 48
    p = tmp / "mark.png"
    render(ICON, p, mark_h, background=True)
    mark = Image.open(p).convert("L")

    img = Image.new("L", (W, H), 255)
    img.paste(mark, (0, (H - mark_h) // 2))

    draw = ImageDraw.Draw(img)
    font = ImageFont.truetype(FONT, 21)
    text = "FIBER"
    left, top, right, bottom = draw.textbbox((0, 0), text, font=font)
    x = mark_h + 4 + (W - mark_h - 4 - (right - left)) // 2 - left
    y = (H - (bottom - top)) // 2 - top
    draw.text((x, y), text, font=font, fill=0)

    rows = []
    for yy in range(H):
        rows.append("".join("1" if img.getpixel((xx, yy)) < 160 else "0" for xx in range(W)))
    header = [
        "P1",
        "# FIBER boot splash, 128x64, 1 = lit. Generated by",
        "# portal/branding/scripts/gen-fiber-assets.py from icon.svg; do not edit.",
        f"{W} {H}",
    ]
    (BRAND / "splash.pbm").write_text("\n".join(header + rows) + "\n")


def main() -> int:
    with tempfile.TemporaryDirectory() as t:
        tmp = Path(t)
        favicon(tmp)
        splash(tmp)
    print(f"wrote {BRAND / 'favicon.ico'} and {BRAND / 'splash.pbm'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
